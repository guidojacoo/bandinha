import { prisma } from "@h59/db";
import { requireSessionUser } from "@/lib/authServer";
import type { DataSource, HealthMetric } from "@h59/db";

const METRICS: { key: HealthMetric; label: string; unit: string; icon: string }[] = [
  { key: "heart_rate", label: "Heart rate", unit: "bpm", icon: "♥" },
  { key: "hrv", label: "HRV", unit: "ms", icon: "≈" },
  { key: "spo2", label: "SpO2", unit: "%", icon: "◯" },
  { key: "blood_pressure", label: "Blood pressure", unit: "mmHg", icon: "◒" },
  { key: "stress", label: "Stress", unit: "/100", icon: "⚡" },
  { key: "steps", label: "Steps (today)", unit: "", icon: "👟" },
  { key: "calories", label: "Calories (today)", unit: "kcal", icon: "🔥" },
];

const SOURCE_LABEL: Record<DataSource, { label: string; pill: string }> = {
  device_realtime: { label: "Measured live from your H59", pill: "pill-good" },
  device_history: { label: "Downloaded from your H59's onboard history", pill: "pill-good" },
  calculated: { label: "Calculated by H59 Health from device readings", pill: "pill-warn" },
  estimated: { label: "Estimated — not a direct sensor reading", pill: "pill-bad" },
};

export default async function HealthPage() {
  const user = await requireSessionUser();
  const dayStart = new Date();
  dayStart.setUTCHours(0, 0, 0, 0);

  const latest = await Promise.all(
    METRICS.map((m) =>
      prisma.healthSample.findFirst({
        where: {
          userId: user.id,
          metric: m.key,
          ...(m.key === "steps" || m.key === "calories" ? { ts: { gte: dayStart } } : {}),
        },
        orderBy: { ts: "desc" },
      }),
    ),
  );

  return (
    <div className="stack" style={{ gap: 20 }}>
      <div>
        <h1 style={{ margin: "0 0 4px", fontSize: 24 }}>Health</h1>
        <p style={{ margin: 0, color: "var(--text-muted)", fontSize: 14, maxWidth: 620 }}>
          Every value below is labeled with where it came from. "Measured" and "downloaded" values come
          straight from your H59's own sensors; "calculated" values are derived by H59 Health; nothing is
          ever shown as a device reading unless the band actually reported it.
        </p>
      </div>

      <div style={{ display: "grid", gridTemplateColumns: "repeat(auto-fill, minmax(260px, 1fr))", gap: 14 }}>
        {METRICS.map((m, i) => {
          const sample = latest[i];
          const src = sample ? SOURCE_LABEL[sample.source] : null;
          return (
            <div key={m.key} className="card stack" style={{ padding: 18, gap: 10 }}>
              <div className="row" style={{ gap: 8, color: "var(--text-muted)", fontSize: 13, fontWeight: 600 }}>
                <span aria-hidden>{m.icon}</span>
                <span>{m.label}</span>
              </div>
              {sample ? (
                <>
                  <div className="row" style={{ alignItems: "baseline", gap: 4 }}>
                    <span style={{ fontSize: 26, fontWeight: 700 }}>
                      {sample.value}
                      {sample.value2 != null ? ` / ${sample.value2}` : ""}
                    </span>
                    {m.unit && <span style={{ fontSize: 13, color: "var(--text-muted)" }}>{m.unit}</span>}
                  </div>
                  <div className="row" style={{ justifyContent: "space-between" }}>
                    <span className={`pill ${src!.pill}`}>{src!.label}</span>
                  </div>
                  <span style={{ fontSize: 12, color: "var(--text-muted)" }}>
                    {new Date(sample.ts).toLocaleString()}
                  </span>
                </>
              ) : (
                <span style={{ fontSize: 14, color: "var(--text-muted)" }}>No data yet</span>
              )}
            </div>
          );
        })}
      </div>

      <div className="card" style={{ padding: 18, fontSize: 13, color: "var(--text-muted)" }}>
        <strong style={{ color: "var(--text)" }}>A note on blood pressure:</strong> the H59 has no real
        onboard blood-pressure history — only an on-demand reading taken while connected. Any "hourly"
        blood-pressure curve you may have seen in QWatch Pro was generated by that app, not measured by the
        device. H59 Health never fabricates that curve — see docs/BLE_PROTOCOL.md.
      </div>
    </div>
  );
}
